import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
const files = {
  'app/care-home.tsx':'Home', 'app/care-hero.tsx':'Home', 'app/care-frame.tsx':'Navigation & footer',
  'app/about-view.tsx':'About', 'app/care-directory.tsx':'Systems', 'app/system-experience.tsx':'System details',
  'app/planning/planning-view.tsx':'Planning', 'app/journeys-view.tsx':'Care journeys',
  'app/customer-reviews.tsx':'Customer reviews', 'app/scope-calculator.tsx':'Archive calculator',
  'app/requests/requests-view.tsx':'My requests', 'app/lead-form.tsx':'Contact form', 'app/review-form.tsx':'Review form',
};
const root=path.resolve(import.meta.dirname,'..'), entries=new Map();
for(const [file,page] of Object.entries(files)){
  const ast=ts.createSourceFile(file,fs.readFileSync(path.join(root,file),'utf8'),ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX);
  function visit(n){
    if(ts.isCallExpression(n)&&ts.isIdentifier(n.expression)&&n.expression.text==='t'&&n.arguments.length>=2&&n.arguments.slice(0,2).every(a=>ts.isStringLiteral(a)||ts.isNoSubstitutionTemplateLiteral(a))){
      const [ar,en]=n.arguments.slice(0,2).map(a=>a.text);const old=entries.get(en);
      if(old){if(!old.pages.includes(page))old.pages.push(page)}else entries.set(en,{ar,en,pages:[page]});
    }
    ts.forEachChild(n,visit);
  }
  visit(ast);
}
fs.writeFileSync(path.join(root,'lib/copy-catalog.ts'),'// Generated by scripts/build-copy-catalog.mjs. Keys match the original English text.\nexport const copyCatalog: { ar: string; en: string; pages: string[] }[] = '+JSON.stringify([...entries.values()],null,2)+';\n');
console.log(`Indexed ${entries.size} editable text entries across ${Object.keys(files).length} components.`);